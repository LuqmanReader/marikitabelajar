'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const music=read('spotify-study-music.js');
const shell=read('workspace.html');
const navigation=read('workspace-shell.js');
const auth=read('auth.js');
const home=read('index.html');
const profile=read('profile-page.js');
const css=read('workspace-shell.css');
for(const file of ['spotify-study-music.js','workspace-shell.js','auth.js','profile-page.js']){
 assert.doesNotThrow(()=>new Function(read(file)),file+' should parse without syntax errors');
}
assert.ok(shell.includes('id="lpContentFrame"'),'Parent workspace must contain one content frame');
assert.ok(shell.includes('class="lp-shell-logo"')&&shell.includes('onerror="this.remove()"'),'Shell logo must have a visible branded fallback when the image fails');
assert.ok(css.includes('.lp-shell-logo img{position:absolute'),'Original logo should cover the branded fallback when loaded');
assert.ok(shell.includes('spotify-study-music.js'),'Parent shell must load Spotify');
assert.ok(shell.includes('id="workspaceMusicButton"'),'Parent shell must expose Study Music button');
assert.ok(navigation.includes("frame.addEventListener('load'"),'Child pages must be navigable');
assert.ok(navigation.includes("event.stopImmediatePropagation()"),'Homepage child music must call the parent');
assert.ok(navigation.includes('LedgerPeerStudyMusic?.open?.()'),'Single parent music controller must open');
assert.ok(navigation.includes('#ledgerpeer-spotify-host{display:none!important}'),'Stale iframe music widgets must stay hidden');
assert.ok(music.includes("window.frameElement?.id === 'lpContentFrame'"),'Child pages must NOT instantiate another player');
assert.ok(music.includes('window.LedgerPeerStudyMusic={open:openPersistentMusic'),'Persistent music controller must be exported');
assert.ok(!music.includes('window.open('),'Study Music must never spawn another tab or popup');
assert.ok(music.includes("location.assign('workspace.html?music=1#'"),'Standalone study pages should enter same-tab music workspace');
assert.ok(auth.includes("'workspace.html#'+encodeURIComponent(destination)"),'Login should open the persistent shell');
assert.ok(home.includes('window.self===window.top'),'Signed-in homepage should enter the shell only when not framed');
assert.ok(profile.includes("'workspace.html#'+encodeURIComponent(route)"),'Finished profile should enter the shell');
assert.ok(navigation.includes("history.replaceState("),'Shell URL should match loaded content');
assert.ok(navigation.includes("if(!names.has(file))return"),'Route must be restricted to known local pages');
assert.ok(css.includes('#lpContentFrame'),'Content iframe must fill the single tab');
assert.ok(read('study-music.html').includes('url=workspace.html?music=1'),'Old popout URL must redirect into the same tab');
console.log('PASS: one-tab persistent Spotify player, authenticated routing, navigation and no popups.');
